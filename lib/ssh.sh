# shellcheck shell=bash
# shellcheck disable=SC2153 # ALIAS (this Mac's short name) is set in common.sh
# Stage: ssh. This Mac's key, GitHub, and logins between your machines.
#
# The repo holds only public material: ssh/keys/<alias>.pub (each machine's user
# key), ssh/hosts/<alias>.pub (each machine's host key, plus an optional
# <alias>.conf with extra ssh_config lines) and ssh/github_known_hosts.

SSH_DIR="$HOME/.ssh"
SSH_KEY="$SSH_DIR/id_ed25519"
KEYS_DIR="$DOTFILES/ssh/keys"
HOSTS_DIR="$DOTFILES/ssh/hosts"
SSHD_DROPIN=/etc/ssh/sshd_config.d/050-dotfiles.conf
SSH_HOST_PUB=/etc/ssh/ssh_host_ed25519_key.pub
AK_BEGIN="# >>> dotfiles: machine keys from ~/dotfiles/ssh/keys (bootstrap.sh replaces this block) >>>"
AK_END="# <<< dotfiles <<<"

stage_ssh() {
	hdr "SSH"
	require_profile
	ensure_ssh_dir
	ssh_key_setup
	ssh_config_include
	# Remote Login first: the host key ssh_capture_this_mac saves only exists once it's on
	ssh_remote_login
	ssh_capture_this_mac
	ssh_refresh
	ssh_github_upload
	ssh_keys_only
}

# Stage ssh-hosts: rebuild the generated files from the repo, with no prompts
stage_ssh_hosts() {
	hdr "SSH keys and hosts"
	ensure_ssh_dir
	ssh_config_include
	ssh_refresh
}

ensure_ssh_dir() {
	if [ ! -d "$SSH_DIR" ]; then
		run mkdir -p "$SSH_DIR"
		run chmod 700 "$SSH_DIR"
	fi
}

has_no_passphrase() {
	ssh-keygen -y -P '' -f "$SSH_KEY" >/dev/null 2>&1
}

ssh_key_setup() {
	if [ -f "$SSH_KEY" ]; then
		ok "key $(tildify "$SSH_KEY") ($(ssh-keygen -lf "$SSH_KEY.pub" | awk '{print $2}'))"
		if has_no_passphrase; then
			warn "The key has no passphrase. Add one, stored in the Keychain:"
			info "  ssh-keygen -p -f ~/.ssh/id_ed25519 && ssh-add --apple-use-keychain ~/.ssh/id_ed25519"
		fi
		return 0
	fi
	info "No SSH key on this Mac yet. A new one is ed25519, with a passphrase saved in the Keychain."
	if ! confirm "Create ~/.ssh/id_ed25519 now?" y; then
		warn "skipped; GitHub, commit signing and logins between your machines all need a key"
		return 0
	fi
	run ssh-keygen -t ed25519 -C "$USER@$ALIAS" -f "$SSH_KEY"
	run ssh-add --apple-use-keychain "$SSH_KEY"
}

# ~/.ssh/config stays yours; it only needs to include config.d/* on its first line,
# so the linked defaults and the generated host aliases apply.
ssh_config_include() {
	local cfg="$SSH_DIR/config" line="Include ~/.ssh/config.d/*"
	if [ -f "$cfg" ] && [ "$(head -n 1 "$cfg")" = "$line" ]; then
		ok "~/.ssh/config includes config.d/*"
		return 0
	fi
	if [ ! -f "$cfg" ]; then
		printf '%s\n' "$line" | write_file "$cfg" 600
		return 0
	fi
	if grep -qxF "$line" "$cfg"; then
		warn "~/.ssh/config includes config.d/*, but not on its first line, so settings above it win"
		return 0
	fi
	backup_copy "$cfg"
	{ printf '%s\n\n' "$line"; cat "$cfg"; } | write_file "$cfg" 600
}

# Put this Mac's user key and host key into the repo, so the other machines trust it
ssh_capture_this_mac() {
	# Redirects, not pipes: write_file must run in this shell to record REPO_CHANGED
	if [ -f "$SSH_KEY.pub" ]; then
		write_file "$KEYS_DIR/$ALIAS.pub" 644 < <(awk -v a="$ALIAS" 'NF >= 2 { print $1, $2, a; exit }' "$SSH_KEY.pub")
	fi
	# macOS creates the host keys when sshd first answers a connection, so a Mac whose
	# Remote Login was just turned on has none until something connects
	if [ ! -r "$SSH_HOST_PUB" ] && [ "$DRY_RUN" != 1 ] && remote_login_on; then
		ssh-keyscan -T 5 -t ed25519 127.0.0.1 >/dev/null 2>&1 || true
	fi
	if [ -r "$SSH_HOST_PUB" ]; then
		write_file "$HOSTS_DIR/$ALIAS.pub" 644 < <(awk 'NF >= 2 { print $1, $2; exit }' "$SSH_HOST_PUB")
	elif [ "$DRY_RUN" = 1 ]; then
		dry "would save this Mac's host key, which macOS creates once Remote Login is on"
	else
		warn "This Mac has no SSH host key yet, so your other Macs can't log in or check who they're talking to."
		info "Turn on Remote Login (System Settings → General → Sharing), then run ./bootstrap.sh ssh again."
	fi
}

ssh_refresh() {
	ssh_known_hosts
	ssh_hosts_include
	ssh_authorized_keys
}

# GitHub's host keys: live from GitHub's API when possible, else the copy in the repo
github_known_hosts() {
	local fresh=""
	if [ "$DRY_RUN" != 1 ] && command -v jq >/dev/null 2>&1; then
		fresh=$(curl -fsSL --max-time 10 https://api.github.com/meta 2>/dev/null |
			jq -r '.ssh_keys[]? | "github.com " + .' 2>/dev/null) || fresh=""
	fi
	if [ -n "$fresh" ]; then
		printf '%s\n' "$fresh"
	else
		cat "$DOTFILES/ssh/github_known_hosts"
	fi
}

host_aliases() {
	local f
	for f in "$HOSTS_DIR"/*.pub; do
		if [ -f "$f" ]; then
			basename "$f" .pub
		fi
	done
}

ssh_known_hosts() {
	local alias
	{
		echo "# Generated by ~/dotfiles/bootstrap.sh from GitHub's published keys and ~/dotfiles/ssh/hosts."
		echo "# Don't edit; it's rewritten on every run."
		github_known_hosts
		for alias in $(host_aliases); do
			awk -v a="$alias" 'NF >= 2 { print a "," a ".local", $1, $2 }' "$HOSTS_DIR/$alias.pub"
		done
	} | write_file "$SSH_DIR/known_hosts.dotfiles" 644
}

ssh_hosts_include() {
	local alias conf line
	{
		echo "# Generated by ~/dotfiles/bootstrap.sh from ~/dotfiles/ssh/hosts. Don't edit; it's rewritten on every run."
		for alias in $(host_aliases); do
			conf="$HOSTS_DIR/$alias.conf"
			echo
			echo "Host $alias"
			# Lines from <alias>.conf come first, because ssh uses the first value it sees
			if [ -f "$conf" ]; then
				while IFS= read -r line; do
					case $line in ""|\#*) continue ;; esac
					printf '\t%s\n' "$line"
				done <"$conf"
			fi
			printf '\tHostName %s\n\tHostKeyAlias %s\n' "$alias" "$alias"
		done
		echo
		echo "# Back to all hosts, for anything that follows this file"
		echo "Host *"
	} | write_file "$SSH_DIR/config.d/dotfiles-hosts" 644
}

ssh_authorized_keys() {
	local ak="$SSH_DIR/authorized_keys" f keys=""
	for f in "$KEYS_DIR"/*.pub; do
		if [ -f "$f" ]; then
			keys="$keys$(grep -vE '^[[:space:]]*(#|$)' "$f" || true)"$'\n'
		fi
	done
	if [ -z "$keys" ]; then
		if [ "$DRY_RUN" = 1 ]; then
			info "no machine keys in the repo yet; a real run adds this Mac's first"
			return 0
		fi
		if [ ! -f "$ak" ]; then
			info "no machine keys in the repo yet"
			return 0
		fi
	fi
	{
		if [ -f "$ak" ]; then
			awk -v b="$AK_BEGIN" -v e="$AK_END" '$0 == b { skip = 1; next } $0 == e { skip = 0; next } !skip' "$ak"
		fi
		if [ -n "$keys" ]; then
			echo "$AK_BEGIN"
			printf '%s' "$keys"
			echo "$AK_END"
		fi
	} | write_file "$ak" 600
}

ssh_github_upload() {
	if ! command -v gh >/dev/null 2>&1; then
		info "gh isn't installed yet (the brew stage installs it); skipping the GitHub key upload"
		return 0
	fi
	[ -f "$SSH_KEY.pub" ] || return 0
	local scopes=admin:public_key,admin:ssh_signing_key blob auth_keys signing_keys
	if ! gh auth status --hostname github.com >/dev/null 2>&1; then
		if ! confirm "Log in to GitHub with gh (opens a browser) to add this Mac's key?" y; then
			info "skipped; add ~/.ssh/id_ed25519.pub on github.com as an authentication key and as a signing key"
			return 0
		fi
		run gh auth login --hostname github.com --git-protocol ssh --skip-ssh-key --web --scopes "$scopes" ||
			{ warn "gh login didn't finish"; return 0; }
	fi
	if [ "$DRY_RUN" = 1 ]; then
		dry "would add $(tildify "$SSH_KEY.pub") to GitHub as an authentication key and as a signing key, unless it's there"
		return 0
	fi
	if ! gh api user/ssh_signing_keys >/dev/null 2>&1; then
		info "gh needs permission to manage SSH keys"
		gh auth refresh --hostname github.com --scopes "$scopes" || { warn "gh didn't get the permission"; return 0; }
	fi
	blob=$(awk '{print $2}' "$SSH_KEY.pub")
	auth_keys=$(gh api --paginate user/keys --jq '.[].key' 2>/dev/null || true)
	signing_keys=$(gh api --paginate user/ssh_signing_keys --jq '.[].key' 2>/dev/null || true)
	case $auth_keys in
		*"$blob"*) ok "GitHub has this key for authentication" ;;
		*) gh ssh-key add "$SSH_KEY.pub" --title "$ALIAS" --type authentication ;;
	esac
	case $signing_keys in
		*"$blob"*) ok "GitHub has this key for signing" ;;
		*) gh ssh-key add "$SSH_KEY.pub" --title "$ALIAS" --type signing ;;
	esac
}

remote_login_on() {
	nc -z -G 1 127.0.0.1 22 >/dev/null 2>&1
}

ssh_remote_login() {
	if remote_login_on; then
		ok "Remote Login is on"
		return 0
	fi
	info "Remote Login is off, so your other machines can't ssh into this Mac."
	if ! confirm "Turn on Remote Login?" y; then
		info "skipped"
		return 0
	fi
	run sudo systemsetup -setremotelogin on || true
	if [ "$DRY_RUN" != 1 ] && ! remote_login_on; then
		warn "Couldn't turn it on from Terminal (it needs Full Disk Access)."
		info "Turn it on in System Settings → General → Sharing → Remote Login, then run ./bootstrap.sh ssh again."
	fi
}

# Turn off password logins, but only once a key login to this Mac has worked
ssh_keys_only() {
	local want
	want="# Written by ~/dotfiles/bootstrap.sh: SSH logins with keys only.
PasswordAuthentication no
KbdInteractiveAuthentication no"
	if [ -f "$SSHD_DROPIN" ] && [ "$(cat "$SSHD_DROPIN")" = "$want" ]; then
		ok "sshd accepts keys only"
		return 0
	fi
	if [ "$DRY_RUN" = 1 ]; then
		dry "would test a key login to this Mac, then write $SSHD_DROPIN (PasswordAuthentication no, KbdInteractiveAuthentication no)"
		return 0
	fi
	if ! remote_login_on; then
		info "Remote Login is off; leaving sshd's password setting alone"
		return 0
	fi
	if ! ssh -o BatchMode=yes -o ConnectTimeout=5 -o StrictHostKeyChecking=yes \
		-o HostKeyAlias="$ALIAS" -o UserKnownHostsFile="$SSH_DIR/known_hosts.dotfiles" \
		-o PreferredAuthentications=publickey localhost true 2>/dev/null; then
		warn "A key login to this Mac didn't work yet, so password logins stay on."
		info "Load the key (ssh-add --apple-use-keychain ~/.ssh/id_ed25519) and run ./bootstrap.sh ssh again."
		return 0
	fi
	if [ "$PROFILE" = work ]; then
		info "On a work Mac, IT may rely on password SSH. Check with them before turning it off."
		if ! confirm "Turn off password logins over SSH on this Mac?" n; then
			info "left as is"
			return 0
		fi
	fi
	printf '%s\n' "$want" | sudo tee "$SSHD_DROPIN" >/dev/null
	sudo chmod 644 "$SSHD_DROPIN"
	local effective
	effective=$(sudo sshd -T 2>/dev/null | tr '[:upper:]' '[:lower:]')
	case $effective in
		*"passwordauthentication no"*"kbdinteractiveauthentication no"*|*"kbdinteractiveauthentication no"*"passwordauthentication no"*)
			ok "sshd now accepts keys only" ;;
		*)
			warn "sshd didn't pick up $SSHD_DROPIN; check with: sudo sshd -T | grep -i authentication" ;;
	esac
}

github_ssh_ok() {
	local out
	out=$(ssh -o BatchMode=yes -o ConnectTimeout=8 -T git@github.com 2>&1 || true)
	case $out in *"successfully authenticated"*) return 0 ;; esac
	return 1
}

# Pushing over HTTPS needs a token; over SSH, this Mac's key (on GitHub by now) is enough
ssh_use_ssh_remote() {
	local url
	url=$(git -C "$DOTFILES" remote get-url origin 2>/dev/null || true)
	case $url in
		https://github.com/*) ;;
		*) return 0 ;;
	esac
	if ! github_ssh_ok; then
		warn "GitHub doesn't accept this Mac's key over SSH yet, so the push goes over HTTPS"
		return 0
	fi
	url="git@github.com:${url#https://github.com/}"
	info "pushing over SSH from now on: origin is $url"
	run git -C "$DOTFILES" remote set-url origin "$url"
}

# Called from bootstrap.sh's summary. Offers to commit and push this Mac's key
# files, so the other machines trust it. The commit holds only those two files.
ssh_publish_keys() {
	[ -n "$ALIAS" ] || return 0
	local status files ahead msg=Update
	status=$(git -C "$DOTFILES" status --porcelain --untracked-files=all -- "ssh/keys/$ALIAS.pub" "ssh/hosts/$ALIAS.pub") || return 0
	[ -n "$status" ] || return 0
	files=$(printf '%s\n' "$status" | cut -c4-)
	case $status in *'??'*) msg=Add ;; esac
	msg="$msg $ALIAS's SSH keys"
	info "This Mac's SSH keys aren't on GitHub yet, so your other Macs don't trust it:"
	printf '%s\n' "$files" | sed 's|^|     ~/dotfiles/|'
	ahead=$(git -C "$DOTFILES" log --oneline '@{u}..HEAD' 2>/dev/null || true)
	if [ -n "$ahead" ]; then
		info "Pushing also sends these commits, which aren't on GitHub yet:"
		printf '%s\n' "$ahead" | sed 's/^/     /'
	fi
	if ! confirm "Commit and push them now?" y; then
		info "To do it later: cd ~/dotfiles && git add ssh && git commit -m \"$msg\" && git pull --rebase && git push"
		info "Then run dotsync on your other Macs."
		return 0
	fi
	if [ -z "$(git -C "$DOTFILES" config user.email || true)" ] || [ -z "$(git -C "$DOTFILES" config user.signingkey || true)" ]; then
		warn "git has no identity or signing key on this Mac yet. Run ./bootstrap.sh git, which offers this again."
		return 0
	fi
	if [ "$DRY_RUN" = 1 ]; then
		dry "would commit them as \"$msg\", switch origin to SSH if it uses HTTPS, and push (rebasing first if another Mac pushed)"
		return 0
	fi
	ssh_use_ssh_remote
	# shellcheck disable=SC2086 # one path per word; aliases have no spaces
	run git -C "$DOTFILES" add -- $files
	# shellcheck disable=SC2086
	if ! run git -C "$DOTFILES" commit -q -m "$msg" -- $files; then
		warn "The commit failed, so nothing was pushed."
		return 0
	fi
	# Rebase only when another Mac pushed in the meantime; --autostash covers other edits in progress
	if run git -C "$DOTFILES" fetch -q &&
		{ git -C "$DOTFILES" merge-base --is-ancestor '@{u}' HEAD 2>/dev/null ||
			run git -C "$DOTFILES" rebase -q --autostash '@{u}'; } &&
		run git -C "$DOTFILES" push -q; then
		ok "pushed \"$msg\". Run dotsync on your other Macs so they trust this one."
	else
		warn "Committed, but not pushed. Fix the error above, then: git -C ~/dotfiles pull --rebase && git -C ~/dotfiles push"
	fi
}

# ./bootstrap.sh ssh --print-keys
ssh_print_keys() {
	local f
	for f in "$KEYS_DIR"/*.pub; do
		if [ -f "$f" ]; then
			cat "$f"
		fi
	done
}

# ./bootstrap.sh ssh --add-host ALIAS [HOSTNAME [USER]]: trust a machine that can't
# run bootstrap itself (Voyager, other servers)
ssh_add_host() {
	local alias=${1:-} host=${2:-${1:-}} user=${3:-} key conf=""
	case $alias in
		""|*[!a-z0-9-]*|-*) die "usage: ./bootstrap.sh ssh --add-host ALIAS [HOSTNAME [USER]]  (ALIAS: lowercase letters, digits, hyphens)" ;;
	esac
	hdr "Adding $alias"
	case $host in
		*.*|*:*) warn "$host goes into a public repo. A short Tailscale name (MagicDNS) is safer than a full name or an IP." ;;
	esac
	info "Fetching $host's host key. Do this on your home network or tailnet, where the answer can be trusted."
	key=$(ssh-keyscan -T 8 -t ed25519 "$host" 2>/dev/null | awk '!/^#/ && NF >= 3 { print $2, $3; exit }')
	[ -n "$key" ] || die "no ed25519 host key from $host (is SSH on there, and is the name right?)"
	write_file "$HOSTS_DIR/$alias.pub" 644 <<<"$key"
	[ "$host" = "$alias" ] || conf="${conf}HostName $host"$'\n'
	[ -z "$user" ] || conf="${conf}User $user"$'\n'
	if [ -n "$conf" ]; then
		write_file "$HOSTS_DIR/$alias.conf" 644 < <(printf '%s' "$conf")
	fi
	stage_ssh_hosts
}
